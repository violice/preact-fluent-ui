import assert from 'node:assert/strict';
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const outputPath = join(root, 'THIRD_PARTY_NOTICES.txt');
// These helpers are bundled into library JS despite being build-time devDependencies.
const bundledPackages = [];

function readText(path) {
  return readFileSync(path, 'utf8').replace(/\r\n/g, '\n').trimEnd();
}

function generate() {
  const lock = JSON.parse(readText(join(root, 'package-lock.json')));
  assert(lock.packages, 'package-lock.json must contain package entries.');
  const sections = [
    '@violice/preact-fluent-ui third-party notices\n\n' +
      'Generated by scripts/generate-third-party-notices.mjs. Do not edit this file.\n' +
      'Includes vendored Fluent icons. Styles helpers are implemented in this library.\n' +
      'Preact is an external peer dependency. Compiler integrations use external build-time dependencies and an optional Vite peer; their implementations are not bundled.',
    readText(join(root, 'licenses/fluent-system-icons.txt')),
  ];

  for (const name of bundledPackages) {
    const packagePath = `node_modules/${name}`;
    const directory = join(root, packagePath);
    const entry = lock.packages[packagePath];
    assert(entry, `Missing lockfile entry for ${name}`);
    const metadata = JSON.parse(readText(join(directory, 'package.json')));
    assert.equal(metadata.name, name, `Installed package name mismatch: ${packagePath}`);
    assert.equal(
      metadata.version,
      entry.version,
      `Installed package version mismatch: ${packagePath}`,
    );
    const files = readdirSync(directory, { withFileTypes: true })
      .filter((file) => file.isFile() && /^(?:licen[cs]e|notice)/i.test(file.name))
      .map((file) => file.name)
      .sort();
    assert(
      files.some((file) => /^licen[cs]e/i.test(file)),
      `Missing license for ${name}`,
    );
    const texts = files.map((file) => {
      const text = readText(join(directory, file));
      assert(text, `Empty license/notice file: ${name}/${file}`);
      return `${file}\n\n${text}`;
    });
    sections.push(
      `${name}@${metadata.version}\nLicense: ${metadata.license ?? entry.license ?? 'See license text below'}\n\n${texts.join('\n\n')}`,
    );
  }
  return `${sections.join(`\n\n${'='.repeat(80)}\n\n`)}\n`;
}

try {
  const args = process.argv.slice(2);
  assert(
    args.length === 0 || (args.length === 1 && args[0] === '--check'),
    'Usage: node scripts/generate-third-party-notices.mjs [--check]',
  );
  const generated = generate();
  if (args.includes('--check')) {
    assert(
      existsSync(outputPath) && readFileSync(outputPath, 'utf8') === generated,
      'THIRD_PARTY_NOTICES.txt is out of date. Run npm run licenses:generate.',
    );
    console.log('Third-party notices are up to date.');
  } else {
    writeFileSync(outputPath, generated);
    console.log('Generated THIRD_PARTY_NOTICES.txt.');
  }
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
}
